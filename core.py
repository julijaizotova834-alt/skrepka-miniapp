def clean_markdown(text: str) -> str:
    if not text:
        return text
    text = re.sub(r'^#{1,6}\s*', '', text, flags=re.MULTILINE)
    text = re.sub(r'\*\*(.+?)\*\*', r'\1', text)
    text = re.sub(r'__(.+?)__', r'\1', text)
    text = re.sub(r'\*(.+?)\*', r'\1', text)
    text = re.sub(r'_(.+?)_', r'\1', text)
    text = re.sub(r'```[a-zA-Z]*\n?', '', text)
    text = re.sub(r'`(.+?)`', r'\1', text)
    text = re.sub(r'^\s*[\*\-]\s+', '• ', text, flags=re.MULTILINE)
    return text.strip()


def build_docx(title: str, body: str) -> BytesIO:
    doc = Document()
    style = doc.styles['Normal']
    style.font.name = 'Calibri'
    style.font.size = Pt(11)
    h = doc.add_paragraph()
    h.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = h.add_run(title.upper())
    run.bold = True
    run.font.size = Pt(16)
    run.font.color.rgb = RGBColor(0x1F, 0x3A, 0x5F)
    doc.add_paragraph()
    for raw_line in body.split('\n'):
        line = raw_line.rstrip()
        if not line.strip():
            doc.add_paragraph()
            continue
        is_numbered_heading = bool(re.match(r'^\d+\.\s+\S', line))
        letters = [c for c in line if c.isalpha()]
        is_caps_heading = (
            len(letters) >= 3
            and all(c.isupper() for c in letters)
            and len(line) < 80
        )
        if is_numbered_heading or is_caps_heading:
            p = doc.add_paragraph()
            r = p.add_run(line)
            r.bold = True
            r.font.size = Pt(12)
            r.font.color.rgb = RGBColor(0x1F, 0x3A, 0x5F)
        elif line.lstrip().startswith('•'):
            doc.add_paragraph(line.lstrip()[1:].strip(), style='List Bullet')
        else:
            doc.add_paragraph(line)
    buf = BytesIO()
    doc.save(buf)
    buf.seek(0)
    return buf


def build_txt(title: str, body: str) -> BytesIO:
    content = f"{title.upper()}\n{'=' * len(title)}\n\n{body}"
    buf = BytesIO(content.encode('utf-8'))
    buf.seek(0)
    return buf


